import localFont from "next/font/local";
import { Fraunces } from "next/font/google";

/**
 * Avenir Book (400) and Medium (500), extracted from the supplied collection.
 * Note: the supplied file is a desktop licence; confirm a web licence before launch.
 */
export const avenir = localFont({
  variable: "--font-avenir",
  display: "swap",
  // Fixed name so the Arabic stack can reference Avenir without its
  // Arial-backed fallback, which would otherwise capture Arabic glyphs.
  declarations: [{ prop: "font-family", value: "avenir" }],
  src: [
    { path: "../public/fonts/avenir-book.woff2", weight: "400", style: "normal" },
    { path: "../public/fonts/avenir-medium.woff2", weight: "500", style: "normal" },
  ],
});

/**
 * Avenir Heavy joins the same "avenir" family, but only Arabic bold text
 * reaches it (for Latin words inside it), so it is not preloaded.
 */
export const avenirHeavy = localFont({
  variable: "--font-avenir-heavy",
  display: "swap",
  preload: false,
  adjustFontFallback: false,
  declarations: [{ prop: "font-family", value: "avenir" }],
  src: [{ path: "../public/fonts/avenir-heavy.woff2", weight: "700", style: "normal" }],
});

/**
 * Arabic brand faces. Both ship a single 400 weight, so globals.css turns off
 * synthetic bold for Arabic and carries emphasis with colour instead.
 *
 * unicode-range limits them to Arabic (plus the space), so Latin words,
 * Western digits, dashes and quotes inside Arabic text fall through to the
 * Latin brand faces. Neither font has those glyphs anyway (Palestine's Latin
 * is not the brand's). It also means English pages never download them.
 *
 * Both are preloaded: Arabic is the default locale, and two small files
 * replace the eight Google files used before.
 *
 * adjustFontFallback is off: its Arial metrics are computed from Latin glyphs,
 * which these fonts lack, so the "fallback" face would be mis-sized.
 *
 * next/font reads its options statically, so the range is repeated as a
 * literal in each call; keep the two in step.
 */

/**
 * Al Tarikh (Diwan): body, labels, buttons, navigation and forms. It keeps
 * harakat (shadda, tanween) visible. The original is an Apple AAT font that
 * other browsers draw as disconnected letters; al-tarikh.woff is generated by
 * `npm run fonts` (scripts/build-arabic-fonts.mjs) with a standard OpenType
 * GSUB, so letters join in every browser. It draws small on its em (alef is 0.51em), so size-adjust brings it up to
 * Avenir's optical size. The metric overrides cover its measured extents,
 * harakat included (-0.61em to 0.79em), so text centres in pills and chips.
 */
export const alTarikh = localFont({
  variable: "--font-arabic-body",
  display: "swap",
  preload: true,
  adjustFontFallback: false,
  declarations: [
    { prop: "unicode-range", value: "U+0600-06FF, U+0750-077F, U+08A0-08FF, U+FB50-FDFF, U+FE70-FEFF, U+200C-200F, U+0020, U+00A0" },
    { prop: "size-adjust", value: "122%" },
    // In the font's own units: size-adjust scales these with the glyphs.
    { prop: "ascent-override", value: "80%" },
    { prop: "descent-override", value: "62%" },
    { prop: "line-gap-override", value: "0%" },
  ],
  src: [{ path: "../public/fonts/al-tarikh.woff", weight: "400", style: "normal" }],
});

/**
 * Palestine: headlines. It has proper OpenType shaping (contextual
 * alternates, marks, kerning) but its harakat are empty glyphs, which is why
 * it is kept to short display text. Its own metrics declare no descent at all,
 * so descenders would hang outside the line box; the overrides restore it.
 * palestine.woff is also generated by `npm run fonts`, which closes the
 * hairline seams its letters otherwise show at every join.
 */
export const palestine = localFont({
  variable: "--font-arabic-display",
  display: "swap",
  preload: true,
  adjustFontFallback: false,
  declarations: [
    { prop: "unicode-range", value: "U+0600-06FF, U+0750-077F, U+08A0-08FF, U+FB50-FDFF, U+FE70-FEFF, U+200C-200F, U+0020, U+00A0" },
    // Its alef stands 0.70em tall, so it is eased down to sit with Al Tarikh.
    { prop: "size-adjust", value: "92%" },
    { prop: "ascent-override", value: "100%" },
    { prop: "descent-override", value: "45%" },
    { prop: "line-gap-override", value: "0%" },
  ],
  src: [{ path: "../public/fonts/palestine.woff", weight: "400", style: "normal" }],
});

/**
 * Fallback for Aquavit until an Adobe Fonts kit ID is provided via
 * NEXT_PUBLIC_ADOBE_KIT_ID. Fraunces shares Aquavit's soft, flared serif feel.
 */
export const fraunces = Fraunces({
  variable: "--font-fraunces",
  display: "swap",
  subsets: ["latin"],
  weight: "variable",
});

export const fontVariables = [
  avenir.variable,
  avenirHeavy.variable,
  alTarikh.variable,
  palestine.variable,
  fraunces.variable,
].join(" ");
